function getRelevantKnowledge(query, maxSections = 4) {
  const normalized = String(query || "").toLowerCase();
  const terms = normalized
    .replace(/[^a-z0-9\s&-]/g, " ")
    .split(/\s+/)
    .filter((term) => term.length >= 2);

  const scored = snaprollKnowledge.map((section) => {
    const haystack =
      `${section.title} ${section.keywords.join(" ")} ${section.content}`.toLowerCase();
    let score = 0;

    for (const term of terms) {
      if (
        section.keywords.some((keyword) => keyword.toLowerCase().includes(term))
      )
        score += 4;
      if (haystack.includes(term)) score += 1;
    }

    if (
      /price|pricing|cost|free|\$|paid|plan|subscription/i.test(normalized) &&
      section.id === "pricing"
    )
      score += 12;
    if (/filter/i.test(normalized) && section.id === "limits-and-filters")
      score += 10;
    if (
      /qr|join|guest|account|download/i.test(normalized) &&
      section.id === "how-it-works"
    )
      score += 8;
    if (
      /create|event|occasion/i.test(normalized) &&
      section.id === "create-event"
    )
      score += 8;
    if (
      /contact|support|email|instagram|tiktok/i.test(normalized) &&
      section.id === "contact"
    )
      score += 10;

    return { section, score };
  });

  const selected = scored
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, maxSections)
    .map((item) => item.section);

  if (selected.length === 0) {
    return snaprollKnowledge.filter((section) =>
      ["overview", "home", "faq"].includes(section.id),
    );
  }

  return selected;
}

